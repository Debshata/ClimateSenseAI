def f(x, d=3):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{d}f}"


def md_table(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False)


def experiment_log():
    lines = ["# Experiment Log", "", "Generated by `scripts/write_docs.py` from `experiments/registry/runs.jsonl` "
             "and the per-run JSON records. Validation metrics only (test results: `results/metrics/test_metrics.json`).", ""]
    rows = [json.loads(l) for l in open(ROOT / "experiments/registry/runs.jsonl", encoding="utf-8")]
    reg = pd.DataFrame(rows).drop_duplicates("run_id", keep="last")
    reg = reg[reg.group != "smoke"]
    lines += [f"Total neural runs recorded: **{len(reg)}** (excluding smoke tests). Total measured GPU training time: "
              f"**{reg.train_time_s.sum() / 3600:.2f} h**.", ""]
    g = reg.groupby("group").agg(runs=("run_id", "size"), mean_val_macro_f1=("val_macro_f1", "mean"),
                                 best_val_macro_f1=("val_macro_f1", "max"), total_time_min=("train_time_s", lambda s: s.sum() / 60))
    lines += ["## Runs by stage", "", md_table(g.reset_index().round(4)), ""]
    lines += ["## Stage chronology", "",
              "1. Smoke tests (2 epochs) of GRU and MAF-Net to verify the pipeline (excluded from results).",
              "2. Initial runs with default hyper-parameters (`experiments/multimodal`).",
              "3. Optuna tuning (`experiments/tuning`, `optuna.db`). The tuning processes were restarted once to cap "
              "PyTorch CPU threads (CPU contention); trials in flight at that moment are recorded as INTERRUPTED. "
              "Because the TPE sampler is seeded, the restarted worker re-proposed some earlier configurations; these "
              "duplicates were served from the run cache and count toward the trial budget. MAF-Net used two parallel "
              "workers (sampler seeds 42 and 43) on one shared study, capped by `MaxTrialsCallback`.",
              "4. Multi-seed retraining of the selected configurations (`experiments/final`).",
              "5. Ablations, horizons, look-back, spatial hold-out.",
              "6. Single held-out test evaluation (`scripts/evaluate_models.py`).", ""]
    for m in ["mafnet", "gru", "transformer"]:
        t = pd.DataFrame(read_json(ROOT / f"experiments/tuning/{m}_trials.json"))
        t["distinct"] = ~t.params.astype(str).duplicated()
        p = pd.json_normalize(t.params)
        tt = pd.concat([t[["number", "state", "value"]], p], axis=1).sort_values("number")
        lines += [f"## Optuna trials — {m}", "",
                  f"{len(t)} trials: {(t.state == 'COMPLETE').sum()} complete, {(t.state == 'PRUNED').sum()} pruned, "
                  f"{(t.state == 'INTERRUPTED').sum()} interrupted; {int(t[t.state.isin(['COMPLETE', 'PRUNED'])].distinct.sum())} distinct finished configurations.", "",
                  md_table(tt.round(4)), ""]
    fv = read_json(ROOT / "experiments/final_val_summary.json")
    lines += ["## Multi-seed validation results", "", md_table(pd.DataFrame(fv).T.reset_index().rename(columns={"index": "model"})[
        ["model", "val_macro_f1_mean", "val_macro_f1_std"]].round(4)), ""]
    (ROOT / "docs/experiment_log.md").write_text("\n".join(lines), encoding="utf-8")


def architecture_doc():
    import torch
    from climatesense.training.trainer import DEFAULTS, build_model_on_cols, feature_sets, get_arrays

    st = read_json(ROOT / "results/metrics/selected_model_test.json")
    rec = read_json(ROOT / "experiments" / st["selected_run"].split("-")[0] / f"{st['selected_run']}.json")
    cfg = rec["config"]
    arr = get_arrays()
    model, cols = build_model_on_cols(cfg, arr)
    fs = feature_sets(cfg, arr)
    names = [arr.feature_names[c] for c in cols]
    per_mod = {m: [arr.feature_names[i] for i in v] for m, v in fs.items()}
    counts = {n: sum(p.numel() for p in mod.parameters()) for n, mod in model.named_children()}
    L = cfg["lookback"]
    lines = ["# Model Architecture — ClimateSense MAF-Net (selected configuration)", "",
             f"Selected run: `{st['selected_run']}` (seed {cfg['seed']}, chosen by validation macro-F1 among five seeds). "
             f"Checkpoint: `{rec['checkpoint']}` (copy in `models/best/`).", "",
             "## Hyper-parameters", "", "| Parameter | Value |", "|---|---|"]
    for k in ["lookback", "horizon", "encoder", "air_encoder", "dry_encoder", "hidden", "d_model", "layers", "heads", "dropout",
              "modality_dropout", "token_self_attention", "fusion", "use_context", "loss", "optimizer", "lr", "weight_decay",
              "batch_size", "epochs", "patience", "seed"]:
        lines.append(f"| {k} | {cfg[k]} |")
    lines += [f"| best epoch | {rec['best_epoch']} of {rec['epochs_run']} run |", "",
              f"**Total trainable parameters: {rec['n_params']:,}**", "", "## Parameters per module", "",
              "| Module | Parameters |", "|---|---|"] + [f"| `{k}` | {v:,} |" for k, v in counts.items()]
    small = max(16, cfg["hidden"] // 2)
    lines += ["", "## Tensor shapes (batch size B)", "", "| Stage | Shape |", "|---|---|",
              f"| Input window (all model features) | B × {L} × {len(cols)} |"]
    for m, v in per_mod.items():
        h = cfg["hidden"] if m == "climate" else small
        lines.append(f"| {m} branch input → encoder output | B × {L} × {len(v)} → B × {h} |")
    lines += [f"| context input → MLP output | B × 8 → B × {cfg['d_model']} |",
              f"| modality tokens (after projection + embedding) | B × {len(per_mod) + int(cfg['use_context'])} × {cfg['d_model']} |",
              f"| attention weights over modalities | B × {len(per_mod) + int(cfg['use_context'])} |",
              f"| fused vector → logits → probabilities | B × {cfg['d_model']} → B × 4 → B × 4 |", "",
              "## Features per branch", ""]
    for m, v in per_mod.items():
        lines.append(f"* **{m}** ({len(v)}): " + ", ".join(f"`{x}`" for x in v))
    lines += ["* **context** (8): `lat_scaled`, `abs_lat_scaled`, `lon_sin`, `lon_cos`, `log_population`, "
              "`bk_normal_annual`, `bk_seasonal_amplitude`, `bk_warming_recent_minus_normal`", "",
              "## Module listing", "", "```", str(model), "```", "",
              "Diagram: `results/figures/architecture_mafnet.png`; equations: IEEE report §VI and notebook 07."]
    (ROOT / "docs/model_architecture.md").write_text("\n".join(lines), encoding="utf-8")
    return rec, cfg


def readme_results(st, mc, ab):
    tm = st["test_metrics"]
    ci = st["ci95_macro_f1_site_block_bootstrap"]
    rows = mc.sort_values("macro_f1", ascending=False)
    t = rows[["model", "modalities", "n_runs", "val_macro_f1", "accuracy", "balanced_accuracy", "macro_f1", "macro_f1_std",
              "weighted_f1", "roc_auc_macro_ovr", "pr_auc_macro"]].copy()
    t.columns = ["Model", "Inputs", "Seeds", "Val macro-F1", "Test acc.", "Test bal. acc.", "Test macro-F1", "± s.d.",
                 "Test W-F1", "Test ROC-AUC", "Test PR-AUC"]
    a = ab.sort_values("macro_f1", ascending=False)[["variant", "modalities", "val_macro_f1", "macro_f1", "macro_f1_std",
                                                      "balanced_accuracy", "roc_auc_macro_ovr"]]
    a.columns = ["Variant", "Inputs", "Val macro-F1", "Test macro-F1", "± s.d.", "Test bal. acc.", "Test ROC-AUC"]
    pc = pd.DataFrame(tm["per_class"]).T
    pc.index = CLASS_NAMES
    pv = st["paired_vs"]
    s = ["## 8. Results (held-out test period 2026-06-03 → 2026-10-12, horizon 1 day)", "",
         f"**Selected MAF-Net** (`{st['selected_run']}`, chosen by validation macro-F1): macro-F1 **{tm['macro_f1']:.3f}** "
         f"(95 % site-block bootstrap CI {ci[0]:.3f}–{ci[1]:.3f}), accuracy **{tm['accuracy']:.3f}**, balanced accuracy "
         f"**{tm['balanced_accuracy']:.3f}**, macro precision {tm['macro_precision']:.3f}, macro recall {tm['macro_recall']:.3f}, "
         f"weighted F1 {tm['weighted_f1']:.3f}, macro ROC-AUC **{tm['roc_auc_macro_ovr']:.3f}**, macro PR-AUC {tm['pr_auc_macro']:.3f}.", "",
         "### Model comparison (mean over seeds; validation used for selection, test reported once)", "",
         t.round(3).astype(object).where(t.notna(), "—").to_markdown(index=False), "",
         "Paired site-block bootstrap of Δ macro-F1 (selected MAF-Net − other) on identical test samples:", "",
         "| vs | Δ macro-F1 | 95 % CI |", "|---|---|---|"]
    s += [f"| {k} | {v['diff']:+.3f} | [{v['ci95'][0]:+.3f}, {v['ci95'][1]:+.3f}] |" for k, v in pv.items()]
    s += ["", "### Per-class test metrics (selected MAF-Net)", "",
          pc[["precision", "recall", "f1", "support", "roc_auc", "pr_auc"]].astype(float).round(3).reset_index().rename(columns={"index": "class"}).to_markdown(index=False), "",
          "### Ablation (3 seeds each)", "", a.round(3).to_markdown(index=False), "",
          "### Figures", "",
          "| | |", "|---|---|",
          "| ![CM](results/figures/confusion_matrix_normalized.png) | ![ROC/PR](results/figures/roc_pr_curves.png) |",
          "| ![Comparison](results/figures/model_comparison.png) | ![Ablation](results/figures/ablation.png) |",
          "| ![Training](results/figures/training_curves.png) | ![Horizons](results/figures/horizons.png) |", "",
          "More: `results/figures/` (EDA, labels, explainability, calibration, Optuna). Tables: `results/tables/`.", "",
          "## 9. Interpretation", ""]
    return s


